// Only immutable runtime resources enter the versioned cache. Source art remains
// in the downloadable source archive; other metadata and licenses stay network-only.
const resources = [];
for (const path of await listFiles(output)) {
  const name = relative(output, path).split('\\').join('/');
  if (name.startsWith('legal/') || name === 'sw.js' || !runtimeExtensions.has(extname(name))) continue;
  const bytes = await readFile(path);
  resources.push({ path: name, sha256: digest(bytes), bytes: bytes.byteLength });
}
if (!resources.some(entry => entry.path === 'index.html')) throw new Error('Missing runtime index.html');
const version = digest(Buffer.concat([
  await readFile(fileURLToPath(import.meta.url)), Buffer.from(JSON.stringify(resources)),
])).slice(0, 24);

const worker = `/* Generated by scripts/postbuild.mjs; never edit build/sw.js. */
'use strict';
const VERSION = ${JSON.stringify(version)};
const RESOURCES = ${JSON.stringify(resources, null, 2)};
const SCOPE = new URL(self.registration.scope);
const CACHE_PREFIX = 'star-chess-party:' + encodeURIComponent(SCOPE.href) + ':';
const CACHE_NAME = CACHE_PREFIX + VERSION;
const INDEX = new URL('index.html', SCOPE).href;
const ENTRIES = new Map(RESOURCES.map(entry => [new URL(entry.path, SCOPE).pathname, entry]));
const hex = buffer => Array.from(new Uint8Array(buffer), byte => byte.toString(16).padStart(2, '0')).join('');

async function fetchVerified(entry) {
  const url = new URL(entry.path, SCOPE).href;
  const response = await fetch(new Request(url, { cache: 'reload', credentials: 'same-origin', redirect: 'error' }));
  if (!response.ok || response.type === 'opaque') throw new Error('Resource unavailable: ' + entry.path);
  const bytes = await response.clone().arrayBuffer();
  const hash = hex(await crypto.subtle.digest('SHA-256', bytes));
  if (hash !== entry.sha256) throw new Error('Resource version mismatch: ' + entry.path);
  return response;
}

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    try {
      // A small bounded queue avoids a memory spike on mobile devices.
      let cursor = 0;
      const pending = await Promise.allSettled(Array.from({ length: Math.min(4, RESOURCES.length) }, async () => {
        while (cursor < RESOURCES.length) {
          const entry = RESOURCES[cursor++];
          await cache.put(new URL(entry.path, SCOPE).href, await fetchVerified(entry));
        }
      }));
      const failed = pending.find(result => result.status === 'rejected');
      if (failed) throw failed.reason;
    } catch (error) {
      await caches.delete(CACHE_NAME);
      throw error;
    }
    // No skipWaiting: an open game keeps its matching HTML, JS, WASM and models.
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter(name => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)
      .map(name => caches.delete(name)));
    // No clients.claim: never adopt an already-loaded page from a different build.
  })());
});

async function serveResource(entry) {
  const url = new URL(entry.path, SCOPE).href;
  let cache;
  try {
    cache = await caches.open(CACHE_NAME);
    const cached = await cache.match(url);
    if (cached) return cached;
  } catch {}
  try {
    // If storage was evicted, accept only the exact original content from the network.
    const response = await fetchVerified(entry);
    // A quota failure must not discard a valid online response. Installation
    // remains all-or-nothing; this is only best-effort repair after eviction.
    try { await cache?.put(url, response.clone()); } catch {}
    return response;
  } catch {
    return new Response('资源版本已更新或离线缓存不可用。请联网后关闭本游戏的全部页面，再重新打开。', {
      status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' },
    });
  }
}

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== SCOPE.origin || !url.pathname.startsWith(SCOPE.pathname)) return;
  const relative = url.pathname.slice(SCOPE.pathname.length);
  if (relative === 'legal' || relative.startsWith('legal/')) return;
  const entry = ENTRIES.get(url.pathname);
  if (entry) { event.respondWith(serveResource(entry)); return; }
  if (request.mode !== 'navigate') return;
  if (url.pathname === SCOPE.pathname) {
    event.respondWith(serveResource(ENTRIES.get(new URL(INDEX).pathname)));
    return;
  }
  // There are no client-side routes. Redirect an offline navigation to the real
  // index so relative asset paths keep working even from a nested URL.
  event.respondWith(fetch(request).catch(() => Response.redirect(INDEX, 302)));
});
`;
await writeFile(join(output, 'sw.js'), worker, 'utf8');
