const root = dirname(dirname(fileURLToPath(import.meta.url)));
const output = join(root, 'build');
const legal = join(output, 'legal');
const digest = value => createHash('sha256').update(value).digest('hex');
const runtimeExtensions = new Set(['.html', '.css', '.js', '.mjs', '.wasm', '.glb', '.webp', '.svg']);

async function listFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.map(async entry => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return listFiles(path);
    return entry.isFile() ? [path] : [];
  }));
  return files.flat().sort();
}

await stat(join(output, 'index.html'));
await mkdir(legal, { recursive: true });
await cp(join(root, 'licenses'), legal, { recursive: true });
